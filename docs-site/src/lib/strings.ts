const TABLES: Record<StringsLocale, Strings> = { root: EN, ko: KO, "zh-cn": ZH, ru: RU, ja: JA };

/**
 * Substitute `{name}` placeholders.
 *
 * Only the placeholders actually supplied are replaced; an unsupplied one stays
 * literally `{count}` in the output. That is deliberate — a template quietly
 * losing its number reads as a finished sentence and ships, while a visible
 * `{count}` is caught the first time anyone looks at the screen.
 */
export function fmt(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, key: string) =>
    key in vars ? String(vars[key]) : whole);
}

export type TFn = (key: string, vars?: Record<string, string | number>) => string;

/**
 * A translator for one locale.
 *
 * Takes a plain `string` key rather than `StringKey` because the guided
 * palette's keys arrive from `shared/m3/regex.ts` typed as the dashboard's own
 * `TKey` union, and narrowing them here would need a cast at every call site.
 * An unknown key returns its own last dotted segment rather than an empty
 * string: a chip labelled `tokNewThing` is ugly and obviously wrong, which is
 * exactly what an untranslated key should look like.
 */
export function translator(locale: StringsLocale): TFn {
  const table = TABLES[locale] ?? EN;
  return (key, vars) => {
    const value = (table as Record<string, string | undefined>)[key]
      ?? (EN as Record<string, string | undefined>)[key];
    return fmt(value ?? key.split(".").pop() ?? key, vars);
  };
}

/** The whole table for a locale, for callers that want direct lookups. */
export function stringsFor(locale: StringsLocale): Strings {
  return TABLES[locale] ?? EN;
}
