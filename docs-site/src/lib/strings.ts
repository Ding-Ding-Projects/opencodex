/**
 * Every string the site's own chrome renders, in the five locales it publishes.
 *
 * `TabStrip` used to carry its own `STRINGS` object with a comment saying a
 * shared dictionary serving one consumer is a layer with nothing in it, and that
 * absorbing it later would be a rename. This is that absorption: the strip, the
 * regex builder, the four tab searches, the site search and the settings search
 * all resolve here, so a locale is complete or it is a type error — not complete
 * in one component and English in the next.
 *
 * Flat, dotted keys rather than nested objects, for one reason: `Strings` is
 * `Record<keyof typeof EN, string>`, so a locale missing a key fails to compile
 * while a locale with different *wording* does not. A nested shape needs a
 * hand-written interface to get the same guarantee, and a hand-written interface
 * is a third place to forget a key.
 *
 * The `regex.*` keys are spelled exactly as the dashboard spells them, because
 * `TOKEN_GROUPS` and `FLAGS` in `shared/m3/regex.ts` carry the dashboard's own
 * key strings on every entry. Matching them means the guided palette translates
 * through this table with no mapping layer, and `t()` falls back to the key's
 * own construct when the dashboard adds a token this table has not caught up
 * with — a chip reading `\p{Script=Han}` with no description is worse than a
 * chip labelled `regex.tokNewThing`, and both are better than a crash.
 *
 * These are the *documentation locales* (the five languages the site publishes),
 * not the language modes of the funny-level rules — English / playful Cantonese /
 * bilingual is a separate axis, owned by the i18n stage, and it layers on top of
 * this table rather than replacing it.
 *
 * What this module deliberately does NOT do: read the DOM, pick a locale for
 * itself, or interpolate anything it was not given. `fmt` substitutes only the
 * placeholders present in the template and leaves an unknown one visible, so a
 * missing variable shows up as `{count}` in review instead of as a plausible
 * sentence with a number silently missing.
 */

