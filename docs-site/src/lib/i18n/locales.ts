/**
 * This stage's copy in the other languages the site renders.
 *
 * Only the keys `deck.ts` adds. Everything the tab strip, the searches and the
 * regex builder say already lives in `src/lib/strings.ts` with its own five
 * complete tables, and restating any of it here would create the exact drift
 * that having one dictionary is supposed to prevent. `index.ts` merges the two.
 *
 * ## Two axes, and why both are represented here
 *
 * `yue` is the **UI language mode** required of every app — playful Hong Kong
 * 廣東話, with `bi` composing it against English at render time. `ja` / `ko` /
 * `ru` / `zh-cn` are the site's **content locales**, which already route the
 * documentation; their entries exist so a reader on `/ja/` gets Japanese chrome
 * without hunting for a setting. `index.ts` explains how the two compose.
 *
 * The funny-level sliders restyle the English and Cantonese voices only, and the
 * settings screen says so in as many words rather than showing a slider that
 * silently does nothing. That is a stated limit, not an oversight: a five-rung
 * voice ladder is a rewrite of every sentence, and inventing one for four
 * languages nobody requested it in would be four dictionaries of guesses.
 */

