/**
 * Copy for the appearance system: the element editor, the colour picker, the
 * font picker and the presets.
 *
 * A separate table from `strings.ts`, and it is meant to stop being one. That
 * module is the site's dictionary and this surface's keys belong in it; they are
 * here because it was being written by another stage at the same moment, and
 * two agents rewriting one 47 KB file is how a locale loses half its keys.
 *
 * So the lookup below is built to make the merge a *deletion*: `appearanceT`
 * asks `strings.ts` first and only falls through to the table here when that
 * table has no answer. Move these entries into `EN`/`KO`/`ZH`/`RU`/`JA` there
 * and every call site keeps working unchanged; then this file's `TABLE` can go
 * without touching a component. Nothing imports the table directly, only the
 * translator, which is what makes that true.
 *
 * Same flat dotted keys and the same `TFn` shape as `strings.ts`, so the two are
 * interchangeable at every call site. Same fallback discipline too: an unknown
 * key renders its last dotted segment rather than an empty string, because a
 * label reading `letterSpacing` is obviously wrong on sight while an empty one
 * looks like a control that simply has no name.
 *
 * These are the five *documentation locales*. The English / playful Cantonese /
 * bilingual language modes and the funny-level sliders are a different axis,
 * owned by the i18n stage, and layer on top of this rather than replacing it.
 */

