const TABLE: Record<StringsLocale, Table> = { root: EN, ko: KO, "zh-cn": ZH, ru: RU, ja: JA };

/**
 * A translator for the appearance surface.
 *
 * The site dictionary is consulted first — both the requested locale and its
 * English base — so once these keys are folded into `strings.ts` the entries
 * here become unreachable and can be deleted in one commit. Until then they are
 * the answer, and every key exists in all five locales because the table type
 * demands it.
 */
export function appearanceT(locale: StringsLocale): TFn {
  const site = stringsFor(locale) as Record<string, string | undefined>;
  const siteBase = stringsFor("root") as Record<string, string | undefined>;
  const own = TABLE[locale] ?? EN;
  return (key, vars) => {
    const value = site[key] ?? siteBase[key]
      ?? (own as Record<string, string | undefined>)[key]
      ?? (EN as Record<string, string | undefined>)[key];
    return fmt(value ?? key.split(".").pop() ?? key, vars);
  };
}
